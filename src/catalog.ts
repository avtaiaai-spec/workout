export function migrate(state: State): State {
  if (state.seeded.includes("personal-v1")) return state;
  return {
    ...state,
    seeded: [...state.seeded, "personal-v1"],
    exercises: [
      ...state.exercises,
      ...catalog.filter((e) => !state.exercises.some((x) => x.id === e.id)),
    ],
    templates: [
      ...state.templates,
      ...seedTemplates().filter(
        (t) => !state.templates.some((x) => x.id === t.id),
      ),
    ],
  };
}
